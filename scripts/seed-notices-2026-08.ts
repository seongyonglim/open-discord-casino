let added = 0, skipped = 0;
for (const d of DRAFTS) {
  if (exists(d.id)) { console.log('건너뜀 (이미 있음):', d.id); skipped++; continue; }
  const r = createNotice({
    id: d.id, date: d.date, kind: d.kind, title: d.title,
    summary: d.summary, sections: d.sections, active: true,
  });
  if (r.ok) { console.log('등록:', d.id); added++; }
  else { console.log('실패:', d.id, r.error); }
}
console.log(`\n등록 ${added}건 · 건너뜀 ${skipped}건`);
