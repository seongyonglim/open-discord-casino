/**
 * 공지사항.
 *
 * 글은 코드에 둔다 — 관리 화면을 따로 만들지 않는다.
 * 이 서비스는 글이 자주 올라오는 곳이 아니고(업데이트가 있을 때만), 코드에 두면
 * 글이 배포와 함께 버전 관리되고 되돌리기도 쉽다. 작성용 로그인·권한·에디터를
 * 만드는 값이 글 몇 개보다 크다.
 *
 * 새 글은 NOTICES 배열 맨 앞에 추가한다(최신이 위). id는 URL에 그대로 쓰이므로
 * 한 번 정하면 바꾸지 않는다 — 링크를 공유한 사람의 주소가 깨진다.
 */

export type NoticeKind = '업데이트' | '밸런스' | '버그 수정' | '신규' | '점검' | '이벤트';

export interface NoticeSection {
  heading: string;
  /** 문단. 각 줄은 그대로 <p>로 나간다. */
  paras?: string[];
  /** 목록. 각 줄은 <li>로 나간다. */
  bullets?: string[];
  /** 표. head는 열 이름, rows는 행. */
  table?: { head: string[]; rows: string[][] };
}

export interface Notice {
  id: string;
  /** YYYY-MM-DD (KST 기준으로 적는다) */
  date: string;
  kind: NoticeKind;
  title: string;
  /** 목록에 한 줄로 보이는 요약 */
  summary: string;
  sections: NoticeSection[];
}

